import pytest

from app.core import screening
from app.models.workspace_search import WorkspaceSearchRun
from tests.screening_pool import make_pool

pytestmark = pytest.mark.anyio

RANKED = (
    "Screening order was prioritised with active learning (naive Bayes over TF-IDF, retrained after each decision; "
    "PaperLab). All decisions were made by the reviewer."
)


async def _prisma(client, workspace):
    return (await client.get(f"/api/workspaces/{workspace.id}/search/prisma")).json()


async def test_no_automation_and_no_criteria_by_default(client, session):
    workspace, _ = await make_pool(session, [("x", None)])
    body = await _prisma(client, workspace)
    assert (body["automation"], body["screening_criteria"]) == ([], None)


async def test_ranked_use_and_criteria_are_reported(client, session):
    workspace, _ = await make_pool(session, [("x", None)])
    workspace.screening_ranked_used = True
    workspace.screening_criteria = "RCTs on sleep in adults"
    await session.flush()
    body = await _prisma(client, workspace)
    assert body["automation"] == [RANKED]
    assert body["screening_criteria"] == "RCTs on sleep in adults"


async def test_suggestion_models_are_named_once_each(client, session):
    workspace, hits = await make_pool(session, [("a", None), ("b", None), ("c", None)])
    hits[0].suggestion_model = hits[1].suggestion_model = "Ollama · qwen3:8b"
    await session.flush()
    body = await _prisma(client, workspace)
    assert body["automation"] == [
        "Title/abstract suggestions were generated by Ollama · qwen3:8b against the stated criteria; "
        "every decision was made by the reviewer."
    ]


async def test_export_states_the_question_and_both_criteria(client, session):
    workspace, _ = await make_pool(session, [])
    await screening.set_criteria(
        session, workspace.id, research_question="Does sleep help?", inclusion="RCTs", exclusion="Animal studies")
    body = (await client.get(f"/api/workspaces/{workspace.id}/search/prisma")).json()
    assert body["screening_criteria"] == (
        "Research question: Does sleep help?\nInclude when: RCTs\nExclude when: Animal studies")


async def test_prisma_notes_identified_is_partial_only_when_a_run_was_cut_short(client, session):  # D266
    workspace, hits = await make_pool(session, [("x", None)])
    assert (await _prisma(client, workspace))["notes"] == []
    run = await session.get(WorkspaceSearchRun, hits[0].run_id)
    run.stats_json = {"cut_short": True, "unfinished_sources": ["arxiv", "crossref"]}
    await session.flush()
    combined = await _prisma(client, workspace)
    per_run = (await client.get(f"/api/workspaces/{workspace.id}/search/prisma", params={"runs": str(run.id)})).json()
    for body in (combined, per_run):
        assert len(body["notes"]) == 1 and "partial" in body["notes"][0] and "arxiv, crossref" in body["notes"][0]


async def test_prisma_notes_paused_sources_so_identified_is_not_mistaken_for_complete(client, session):  # M62
    workspace, hits = await make_pool(session, [("x", None)])
    run = await session.get(WorkspaceSearchRun, hits[0].run_id)
    run.stats_json = {"paused_sources": ["arxiv", "crossref"]}
    await session.flush()
    body = await _prisma(client, workspace)
    assert len(body["notes"]) == 1
    assert "paused at 200 results per source for 2 sources; more can be fetched" in body["notes"][0]
    assert "partial" not in body["notes"][0]  # not the time-limit note
    run.stats_json = {}  # after Continue finishes the sources, the note goes away
    await session.flush()
    assert (await _prisma(client, workspace))["notes"] == []
